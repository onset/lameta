// --------------------------------------------------------------------- helpers

function session(
  ctx: Context,
  folder: string,
  spec: SessionSpec | string,
  why: string,
  targets: string,
  metadataFileName = `${folder}.session`,
) {
  const rel = `${S}/${folder}/${metadataFileName}`;
  ctx.w.file(rel, typeof spec === "string" ? spec : lametaSession(themed(folder, spec)));
  ctx.w.note(`${S}/${folder}`, why, targets);
}

function person(
  ctx: Context,
  folder: string,
  spec: PersonSpec | string,
  why: string,
  targets: string,
  metadataFileName = `${folder}.person`,
) {
  const rel = `${P}/${folder}/${metadataFileName}`;
  ctx.w.file(
    rel,
    typeof spec === "string"
      ? spec
      : lametaPerson({
          name: folder,
          primaryOccupation: theme.themedOccupation(folder),
          description: ml.partlyTranslatedText(
            ml.themedBiographies(folder, folder),
            `${folder}|description`,
          ),
          notes: theme.themedNotes(folder),
          ...spec,
        }),
  );
  ctx.w.note(`${P}/${folder}`, why, targets);
}

// fills in the themed title, description and notes that a case does not set itself
function themed(folder: string, spec: SessionSpec): SessionSpec {
  return {
    id: folder,
    ...spec,
    title:
      spec.title === undefined || spec.title === folder
        ? ml.partlyTranslatedText(ml.themedTitles(folder), `${folder}|title`)
        : spec.title,
    description:
      spec.description ??
      ml.partlyTranslatedText(ml.themedDescriptions(folder), `${folder}|description`),
    notes: spec.notes ?? theme.themedNotes(folder),
  };
}

// a media or other file, with a .meta sidecar unless meta is false
function addFile(
  ctx: Context,
  rel: string,
  opts: { meta?: string | false; content?: Buffer; label?: string } = {},
) {
  const base = path.basename(rel);
  const ext = base.includes(".") ? base.slice(base.lastIndexOf(".") + 1) : "";
  ctx.w.file(rel, opts.content ?? ctx.content.make(ext, opts.label ?? path.basename(rel)));
  if (opts.meta !== false) {
    ctx.w.file(
      `${rel}.meta`,
      opts.meta ?? metaFile({ notes: `Sidecar for ${path.basename(rel)}` }),
    );
  }
}

