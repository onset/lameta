// Generates a lameta project that holds every case that has hurt lameta or plausibly
// could. See ../README.md, "Torture project".
//
//   pnpm exec tsx sample-data-generator/torture/generate-torture-project.ts <projectFolder> [--hostile-names] [--blocking]
//       [--large-media] [--archive-config ELAR] [--bulk-sessions 800] [--bulk-people 240]
//       [--size <sessions>] [--no-cases]
//
// --size makes the bulk part at a given number of sessions, with people, files and problems
// in proportion, so that one project can be measured at several sizes. --no-cases leaves out
// the hand-made hard cases, so that the smallest sizes hold only the bulk.
//
// The .sprj takes the name of <projectFolder>. Without flags, the project holds only
// names that git can check out on Windows, macOS and Linux; that is the version
// committed in "sample data".

import * as fs from "fs";
import * as path from "path";
import { writeBulk } from "./bulk";
import { Context, writePeople, writeProject, writeSessions } from "./cases";
import { ContentMaker } from "./content";
import { writeBlockingCases, writeHostileNames } from "./hostile";
import { writeLargeMedia } from "./large";
import { findFfmpeg } from "./media";
import { CaseRecord, ProjectWriter } from "./writer";

const kCasesDocument = "OtherDocuments/torture-cases.md";

function usage(): never {
  console.error(
    "Usage: tsx generate-torture-project.ts <projectFolder> [--hostile-names] [--blocking] [--large-media] [--archive-config <name>] [--bulk-sessions <n>] [--bulk-people <n>] [--size <n>] [--no-cases]",
  );
  process.exit(1);
}

function parseArgs(argv: string[]) {
  const opts = {
    folder: "",
    hostileNames: false,
    blocking: false,
    largeMedia: false,
    archiveConfiguration: "ELAR",
    bulkSessions: 800,
    bulkPeople: 240,
    cases: true,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--hostile-names") opts.hostileNames = true;
    else if (a === "--blocking") opts.blocking = true;
    else if (a === "--large-media") opts.largeMedia = true;
    else if (a === "--archive-config") opts.archiveConfiguration = argv[++i] ?? usage();
    else if (a === "--bulk-sessions") opts.bulkSessions = Number(argv[++i] ?? usage());
    else if (a === "--bulk-people") opts.bulkPeople = Number(argv[++i] ?? usage());
    else if (a === "--size") {
      opts.bulkSessions = Number(argv[++i] ?? usage());
      opts.bulkPeople = Math.max(1, Math.round(opts.bulkSessions * 0.3));
    } else if (a === "--no-cases") opts.cases = false;
    else if (a.startsWith("--")) usage();
    else if (!opts.folder) opts.folder = a;
    else usage();
  }
  if (!opts.folder) usage();
  const isCount = (n: number) => Number.isInteger(n) && n >= 0;
  if (!isCount(opts.bulkSessions) || !isCount(opts.bulkPeople)) usage();
  // every bulk session credits bulk people
  if (opts.bulkSessions > 0 && opts.bulkPeople === 0) usage();
  return opts;
}

// Only ever delete a folder that this generator made.
function clearPreviousOutput(root: string, keepLargeMedia: boolean) {
  if (!fs.existsSync(root)) return;
  const entries = fs.readdirSync(root);
  if (entries.length === 0) return;
  if (!fs.existsSync(path.join(root, ...kCasesDocument.split("/")))) {
    console.error(
      `${root} is not empty and was not made by this generator (no ${kCasesDocument}). Give an empty or new folder.`,
    );
    process.exit(1);
  }
  for (const entry of entries) {
    const p = path.join(root, entry);
    if (entry === "Sessions" && keepLargeMedia) {
      for (const s of fs.readdirSync(p))
        if (s !== "BIG_media") fs.rmSync(path.join(p, s), { recursive: true, force: true });
    } else {
      fs.rmSync(p, { recursive: true, force: true });
    }
  }
}

function casesDocument(projectName: string, records: CaseRecord[], notes: string[]): string {
  const tiers: Array<[string, string]> = [
    ["portable", "Committed; every name checks out on Windows, macOS and Linux"],
    ["hostile", "--hostile-names and --blocking; never committed"],
    ["large", "--large-media; never committed"],
  ];
  const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
  let md = `# Cases in ${projectName}\n\nGenerated by \`sample-data-generator/torture/generate-torture-project.ts\`. Each row is a folder or file, why it is there, and the lameta code it aims at.\n`;
  for (const n of notes) md += `\n${n}\n`;
  for (const [tier, title] of tiers) {
    const rows = records.filter((r) => r.tier === tier);
    if (rows.length === 0) continue;
    md += `\n## ${tier}: ${title}\n\n| Path | Why | Aims at |\n| --- | --- | --- |\n`;
    for (const r of rows) md += `| \`${cell(r.path)}\` | ${cell(r.why)} | ${cell(r.targets)} |\n`;
  }
  return md;
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const root = path.resolve(opts.folder);
  const projectName = path.basename(root);
  clearPreviousOutput(root, opts.largeMedia);
  fs.mkdirSync(root, { recursive: true });

  const ffmpeg = findFfmpeg();
  const w = new ProjectWriter(root, "portable");
  const content = new ContentMaker(ffmpeg);
  const ctx: Context = { w, content, archiveConfiguration: opts.archiveConfiguration };

  writeProject(ctx, projectName);
  if (opts.cases) {
    writePeople(ctx);
    writeSessions(ctx);
  }
  writeBulk(ctx, opts.bulkSessions, opts.bulkPeople);

  const notes: string[] = [];
  if (opts.hostileNames) {
    w.tier = "hostile";
    writeHostileNames(ctx);
  }
  if (opts.blocking) {
    w.tier = "hostile";
    writeBlockingCases(ctx);
  }
  if (opts.largeMedia) {
    w.tier = "large";
    const skipped = writeLargeMedia(ctx, ffmpeg);
    if (skipped.length) notes.push(`Not generated: ${skipped.join(", ")}.`);
  }
  if (!ffmpeg)
    notes.push("ffmpeg was not found, so compressed audio, video and JPEG files are stand-ins.");
  if (content.missingEncoders.length)
    notes.push(`No encoder for: ${content.missingEncoders.join(", ")}; those files are stand-ins.`);

  w.tier = "portable";
  w.file(kCasesDocument, casesDocument(projectName, w.records, notes));
  console.log(`Wrote ${w.records.length} cases to ${root}`);
  for (const n of notes) console.log(n);
}

main();
